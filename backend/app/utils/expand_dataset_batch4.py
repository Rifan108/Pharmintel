def run():
    target_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "global_medicine_dataset.py")
    with open(target_path, "r", encoding="utf-8") as f:
        content = f.read()

    if "MED-IND-200" in content:
        print("Dataset already contains MED-IND-200. Skipping.")
        return True

    import pprint
    med_code = pprint.pformat(ADDITIONAL_MEDICINES_4, indent=4, width=120)
    med_inner = med_code.strip()[1:-1].strip()

    inter_code = pprint.pformat(ADDITIONAL_INTERACTIONS_4, indent=4, width=120)
    inter_inner = inter_code.strip()[1:-1].strip()

    parts = content.split("VERIFIED_ADDITIONAL_INTERACTIONS = [")
    first_part = parts[0]
    second_part = parts[1]

    last_b1 = first_part.rfind("]")
    new_first = first_part[:last_b1].rstrip() + ",\n" + med_inner + "\n]\n\n"

    last_b2 = second_part.rfind("]")
    new_second = second_part[:last_b2].rstrip() + ",\n" + inter_inner + "\n]\n"

    final_content = new_first + "VERIFIED_ADDITIONAL_INTERACTIONS = [\n" + new_second

    with open(target_path, "w", encoding="utf-8") as f:
        f.write(final_content)

    print("Successfully expanded global_medicine_dataset.py through MED-IND-200 and added clinical interaction rules!")
    return True

if __name__ == "__main__":
    run()
