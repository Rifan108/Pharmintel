def expand():
    target_file = os.path.join("backend", "app", "utils", "global_medicine_dataset.py")
    with open(target_file, "r", encoding="utf-8") as f:
        content = f.read()

    # Find the end of VERIFIED_GLOBAL_MEDICINES list
    med_list_marker = "]\\n\\n# Curated Pairwise Interaction Rules across the Expanded Compendium"
    alt_marker = "]\\n\\n# Curated Pairwise Interaction Rules"
    
    # Let's find VERIFIED_ADDITIONAL_INTERACTIONS = [
    if "VERIFIED_ADDITIONAL_INTERACTIONS = [" not in content:
        print("ERROR: Could not find VERIFIED_ADDITIONAL_INTERACTIONS in file")
        return False

    parts = content.split("VERIFIED_ADDITIONAL_INTERACTIONS = [")
    first_part = parts[0]
    second_part = parts[1]

    # In first_part, find the last "]" before the end
    last_bracket_idx = first_part.rfind("]")
    if last_bracket_idx == -1:
        print("ERROR: Could not find end bracket for VERIFIED_GLOBAL_MEDICINES")
        return False

    # Insert ADDITIONAL_MEDICINES_CODE before the last bracket
    updated_first_part = (
        first_part[:last_bracket_idx].rstrip() +
        ",\\n" +
        ADDITIONAL_MEDICINES_CODE.strip() +
        "\\n]\\n\\n"
    )

    # In second_part, find the last "]" which closes VERIFIED_ADDITIONAL_INTERACTIONS
    last_bracket_rule_idx = second_part.rfind("]")
    if last_bracket_rule_idx == -1:
        print("ERROR: Could not find end bracket for VERIFIED_ADDITIONAL_INTERACTIONS")
        return False

    updated_second_part = (
        second_part[:last_bracket_rule_idx].rstrip() +
        ",\\n" +
        ADDITIONAL_INTERACTIONS_CODE.strip() +
        "\\n]\\n"
    )

    full_updated = updated_first_part + "VERIFIED_ADDITIONAL_INTERACTIONS = [\\n" + updated_second_part

    with open(target_file, "w", encoding="utf-8") as f:
        f.write(full_updated)

    print("Successfully updated global_medicine_dataset.py!")
    return True

if __name__ == "__main__":
    expand()
